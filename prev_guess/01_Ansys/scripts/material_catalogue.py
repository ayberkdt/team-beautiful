"""Generate the material catalogue (prev_guess/01_Ansys/docs/15_material_catalogue.md) from the sourced pool.

    python prev_guess/01_Ansys/scripts/material_catalogue.py

Every number in the catalogue is read from `aerokit.materials.pool`; tags follow each value as a superscript-free
suffix (D read from the primary source, S secondary, Y estimate). Index tables come from `pool.rank_pool`.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = next(p for p in Path(__file__).resolve().parents if (p / "pyproject.toml").is_file())  # repo root
sys.path.insert(0, str(ROOT / "src"))

from aerokit.materials import pool  # noqa: E402

OUT = ROOT / "prev_guess" / "01_Ansys" / "docs" / "15_material_catalogue.md"
FAMILIES = [("aluminium", "Aluminium alloys"), ("titanium", "Titanium alloys"), ("steel", "Steels"),
            ("nickel", "Nickel alloys"), ("magnesium", "Magnesium alloys"), ("composite", "Composites"),
            ("polymer", "Polymers"), ("core", "Sandwich cores")]
MECH = [("rho", "ρ (kg/m³)", 0), ("E", "E (GPa)", 1), ("Fty", "Fty (MPa)", 0), ("Ftu", "Ftu (MPa)", 0),
        ("fatigue", "Fatigue (MPa)", 0)]
THERM = [("k", "k (W/m K)", 1), ("cte", "α (10⁻⁶/K)", 1), ("Tmax", "Tmax (°C)", 0), ("co2", "CO₂ (kg/kg)", 1)]
CASES = [("tie_stiff", "stiff tie E/ρ"), ("beam_stiff", "stiff beam E^½/ρ"), ("panel_stiff", "stiff panel E^⅓/ρ"),
         ("tie_strong", "strong tie σ/ρ"), ("beam_strong", "strong beam σ^⅔/ρ"),
         ("panel_strong", "strong panel σ^½/ρ")]


def cell(p: dict, key: str, nd: int) -> str:
    if key not in p:
        return "–"
    v = p[key]
    return f"{v['value']:.{nd}f} {v['tag']}"


def main() -> int:
    mats = pool.load()["materials"]
    lines = ["# 15 · Material catalogue (generated from the sourced pool)", "",
             "Generated by `python prev_guess/01_Ansys/scripts/material_catalogue.py` from `aerokit.materials.pool` "
             "(data: `prev_guess/01_Ansys/research/Malzeme havuzu/materials_pool.json`, 31 materials, every value with its source "
             "and a tag: D read from the primary source, S secondary, Y estimate or stand-in). Strength columns mix "
             "MIL-HDBK-5J A/S-basis allowables and datasheet typical values; the source string in the pool says "
             "which. Fatigue is the stated condition of each source (mostly 10⁷ cycles, R = −1). Do not edit this "
             "file by hand: change the pool and regenerate.", ""]
    for fam, title in FAMILIES:
        names = [n for n, r in mats.items() if r.get("family") == fam]
        if not names:
            continue
        lines += [f"## {title}", "", "Mechanical:", "", "| Material | " + " | ".join(c[1] for c in MECH) + " |",
                  "|---|" + "---:|" * len(MECH)]
        for n in names:
            p = mats[n]["properties"]
            lines.append(f"| {n} | " + " | ".join(cell(p, k, nd) for k, _, nd in MECH) + " |")
        lines += ["", "Thermal, carbon and routes:", "",
                  "| Material | " + " | ".join(c[1] for c in THERM) + " | Routes |",
                  "|---|" + "---:|" * len(THERM) + "---|"]
        for n in names:
            p = mats[n]["properties"]
            routes = ", ".join(mats[n].get("routes", []))[:60]
            lines.append(f"| {n} | " + " | ".join(cell(p, k, nd) for k, _, nd in THERM) + f" | {routes} |")
        lines.append("")
    lines += ["## Performance-index rankings over the pool", "",
              "Relative mass of a part of fixed geometry family and fixed stiffness or strength (1.00 = lightest). "
              "Materials without the property are left out (composites and polymers have no Fty entry).", ""]
    for case, title in CASES:
        r = pool.rank_pool(case)[:6]
        lines.append(f"- **{title}**: " + " · ".join(f"{x.name} {x.relative_mass:.2f}" for x in r))
    lines += ["", "## The same indices with embodied CO₂ instead of mass", "",
              "Ranking by ρ·CO₂ in place of ρ: the part with the least production CO₂. For a part that flies, "
              "the use phase is about 98 % of life CO₂ (docs 11–13), so this ranking matters only when there is no "
              "use phase (ground equipment, tooling, a satellite judged on production).", ""]
    for case, title in CASES[1:3] + CASES[4:5]:
        r = pool.rank_pool(case, co2=True)[:6]
        lines.append(f"- **{title}, CO₂**: " + " · ".join(f"{x.name} {x.relative_mass:.2f}" for x in r))
    lines += ["", "## Flags and notes per material", ""]
    for n, rec in mats.items():
        flags = "; ".join(rec.get("flags", []))
        note = rec.get("notes", "").replace("\n", " ")
        if flags or note:
            lines.append(f"- **{n}** — {flags}{' · ' if flags and note else ''}{note[:300]}")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(mats)} materials)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
