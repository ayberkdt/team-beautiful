"""Generate ``docs/references.md`` from the bibliography registry and the ``@cite`` decorators.

Usage::

    python scripts/build_references.py            # write docs/references.md
    python scripts/build_references.py --check    # exit 1 if the file is out of date

The page lists every reference with the functions that cite it, so a reader can go from a
formula in the code to its source and back.
"""
from __future__ import annotations

import argparse
import importlib
import inspect
import pkgutil
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import aerokit  # noqa: E402
from aerokit.references import REFERENCES  # noqa: E402

OUT = ROOT / "docs" / "references.md"


def citations() -> dict[str, list[str]]:
    """Map reference key → sorted list of ``module.qualname`` that cite it."""
    users: dict[str, set[str]] = defaultdict(set)
    for info in pkgutil.walk_packages(aerokit.__path__, "aerokit."):
        if info.name.startswith("aerokit.cli"):
            continue
        mod = importlib.import_module(info.name)
        for _, obj in vars(mod).items():
            if getattr(obj, "__module__", None) != mod.__name__:
                continue
            candidates = [obj]
            if inspect.isclass(obj):
                members = vars(obj).values()
                candidates += [v for v in members if callable(v) or isinstance(v, staticmethod | classmethod)]
            for c in candidates:
                fn = getattr(c, "__func__", c)
                for key in getattr(fn, "__references__", ()):
                    users[key].add(f"{mod.__name__}.{getattr(fn, '__qualname__', getattr(fn, '__name__', '?'))}")
    return {k: sorted(v) for k, v in users.items()}


def render() -> str:
    used = citations()
    lines = ["# References", "",
             "Generated by `python scripts/build_references.py` from `src/aerokit/references/`; do not edit by hand.",
             "Each entry lists the functions that cite it with `@cite`. Bibliographic details were compiled "
             "from the sources named in the code; entries whose source PDF is in `references/` were checked "
             "against it (MIL-HDBK-5J, competition documents).", "",
             f"{len(REFERENCES)} references · {sum(len(v) for v in used.values())} citations · "
             f"{sum(1 for k in REFERENCES if k not in used)} not yet cited by code.", ""]
    for key, ref in REFERENCES.items():
        lines.append(f"### `{key}`")
        lines.append("")
        lines.append(ref.format() + (f" — {ref.note}" if ref.note else ""))
        if key in used:
            lines.append("")
            lines.append("Cited by: " + ", ".join(f"`{u}`" for u in used[key]))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if docs/references.md is out of date")
    a = ap.parse_args()
    text = render()
    if a.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is out of date; run python scripts/build_references.py", file=sys.stderr)
            return 1
        print(f"{OUT} is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({len(REFERENCES)} references)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
