"""Analytic (closed-form) relations behind the trade-off figures, generated from the organisers' raw data.

Every life-cycle phase in the card is proportional to part mass, so life-cycle CO₂ is a straight line through the
origin: C = c·m. All other relations (equal-CO₂ mass, equal-CO₂ volume, saving, extra cost) follow from the slopes.

python -I 01_Ansys/submission/trade_off/equations.py
  → writes the block between <!-- EQ:START --> and <!-- EQ:END --> in TRADEOFF_SECTION.md (and prints it)
"""
import json
import math
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
HERE = Path(__file__).resolve().parent
R = json.loads((HERE.parents[1] / "official_2026-11-05" / "analysis" / "organiser_materials.json")
               .read_text(encoding="utf-8"))["materials"]
gm = lambda r: math.sqrt(r[0] * r[1])                 # Granta point value = geometric mean of the range
USE = 4000 * 180 * 0.000468                            # card: 720 000 km × 0.000468 kg CO2/(kg·km)
TR = 500 * 0.241 / 1000                                # card transport formula per tonne (report: 18.5 kg for 152 kg)
DI = 7.45 / 152                                        # organisers' eco audit p.2: 7.45 kg for 152 kg
V0, M0 = 0.019400, 152.27                              # m³ and kg of the initial S275N part


def ph(k):
    v, p = gm(R[k]["co2_virgin"]), gm(R[k]["co2_powder"])
    rec = gm(R[k]["co2_recycle"])
    return {"virgin": v, "powder": p, "transport": TR, "use": USE, "disposal": DI, "c": v + p + TR + USE + DI,
            "eol": -(v - rec), "rho": gm(R[k]["rho"]), "price": gm(R[k]["price"])}


S, T, A = ph("S275N"), ph("Ti811SA"), ph("Al2618T6")
C0, K0 = M0 * S["c"] / 1000, M0 * S["price"]
m_tie = C0 * 1000 / T["c"]
EQ = {
    "cS": S["c"], "cT": T["c"], "cA": A["c"],
    "kS": S["rho"] * V0 * S["c"] / 1e5, "kT": T["rho"] * V0 * T["c"] / 1e5, "kA": A["rho"] * V0 * A["c"] / 1e5,
    "mS_per_mT": T["c"] / S["c"], "mT_per_mS": S["c"] / T["c"],
    "fS_per_fT": T["rho"] * T["c"] / (S["rho"] * S["c"]), "fT_per_fS": S["rho"] * S["c"] / (T["rho"] * T["c"]),
    "same_vol": T["rho"] / S["rho"], "C0": C0, "K0": K0, "m_tie": m_tie,
    "pS": S["price"], "pT": T["price"], "m_cost_parity": K0 / T["price"],
    "cS_eol": S["c"] + S["eol"], "cT_eol": T["c"] + T["eol"],
}
EQ["mS_per_mT_eol"] = EQ["cT_eol"] / EQ["cS_eol"]


def block():
    e = EQ
    return f"""<!-- EQ:START (generated by equations.py — do not edit by hand) -->
### 3.5 Analytic relations

Every phase prescribed by the card is proportional to the part mass m, so the life-cycle (first-life) footprint is a
straight line through the origin, C = c·m, with c the sum of the phase factors per kilogram [1–3]:

| Phase (kg CO₂-eq per kg of part) | S275N | Ti-8Al-1Mo-1V |
|---|---:|---:|
| Material, virgin grade | {S['virgin']:.2f} | {T['virgin']:.2f} |
| Manufacture, metal powder forming | {S['powder']:.2f} | {T['powder']:.2f} |
| Transport, 500 km × 0.241 kg/(t·km) | {TR:.2f} | {TR:.2f} |
| Use, 720 000 km × 0.000468 kg/(kg·km) | {USE:.2f} | {USE:.2f} |
| Disposal | {DI:.3f} | {DI:.3f} |
| **c, life-cycle (first life)** | **{S['c']:.1f}** | **{T['c']:.1f}** |

With m in kg and C in t CO₂-eq:

- (1) C_S = {e['cS'] / 1000:.4f} · m_S  and  C_Ti = {e['cT'] / 1000:.4f} · m_Ti  (Al 2618-T6: C_Al = {e['cA'] / 1000:.4f} · m_Al)
- (2) Equal CO₂: **m_S = {e['mS_per_mT']:.3f} · m_Ti**, i.e. m_Ti = {e['mT_per_mS']:.3f} · m_S — one kilogram of titanium "costs" as much
  CO₂ over the life as {e['mS_per_mT']:.2f} kg of steel.
- (3) In volume (f = % of the initial 19.4 L design): C_S = {e['kS']:.4f} · f_S and C_Ti = {e['kT']:.4f} · f_Ti; equal CO₂ when
  **f_S = {e['fS_per_fT']:.3f} · f_Ti** (f_Ti = {e['fT_per_fS']:.3f} · f_S).
- (4) Same geometry: m_Ti = {e['same_vol']:.4f} · m_S (density ratio).
- (5) Saving against the initial part ({M0:.2f} kg, {C0:.2f} t): **ΔC = {C0:.2f} − {e['cT'] / 1000:.4f} · m_Ti**, or
  ΔC/C₀ = 1 − m_Ti / {m_tie:.1f}; titanium breaks even with the initial part at m_Ti = {m_tie:.1f} kg.
- (6) Material cost (price × mass): K_S = {e['pS']:.3f} · m_S, K_Ti = {e['pT']:.2f} · m_Ti; extra cost against the
  initial part **ΔK = {e['pT']:.2f} · m_Ti − {K0:.1f}** USD (cost parity only below m_Ti = {e['m_cost_parity']:.1f} kg).
- (7) Cost of carbon avoided: **ΔK/ΔC = ({e['pT']:.2f} · m_Ti − {K0:.1f}) / ({C0:.2f} − {e['cT'] / 1000:.4f} · m_Ti)** USD per t.

Including the end-of-life recycling credit [2] the slopes become {e['cS_eol']:.1f} (S275N) and {e['cT_eol']:.1f}
(Ti-8Al-1Mo-1V) kg/kg, and (2) becomes m_S = {e['mS_per_mT_eol']:.3f} · m_Ti: the titanium penalty per kilogram shrinks
from {100 * (e['mS_per_mT'] - 1):.1f} % to {100 * (e['mS_per_mT_eol'] - 1):.1f} %.
<!-- EQ:END -->"""


if __name__ == "__main__":
    b = block()
    md = HERE / "TRADEOFF_SECTION.md"
    s = md.read_text(encoding="utf-8")
    if "<!-- EQ:START" in s:
        s = s[:s.index("<!-- EQ:START")] + b + s[s.index("<!-- EQ:END -->") + len("<!-- EQ:END -->"):]
    else:                                             # insert before the figure captions
        s = s.replace("---\n\n### Figure captions", b + "\n\n---\n\n### Figure captions")
    md.write_text(s, encoding="utf-8")
    (HERE / "equations.json").write_text(json.dumps(EQ, indent=1), encoding="utf-8")
    print(b)
